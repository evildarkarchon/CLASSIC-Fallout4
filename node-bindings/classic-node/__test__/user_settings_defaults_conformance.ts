import * as classic from "../index.js";

/** Project all real typed default values and their provenance into the receipt. */
export function observeDefaults(): Record<string, unknown> {
  const snapshot = classic.publishedUserSettingsDefaults();
  const groups: Record<string, any> = {update: snapshot.updatePreferences, scan: snapshot.crashLogScanSettings, setup: snapshot.gameSetupSettings, preferences: snapshot.frontendState.preferences, tui: snapshot.frontendState.tui};
  for (const tab of ["mainTab", "backupsTab", "articlesTab", "resultsTab"]) groups[tab] = (snapshot.frontendState.windowGeometry as any)[tab];
  const projection: Record<string, unknown> = {};
  projection["update.update_check"] = groups.update.updateCheck;
  projection["update.update_check_origin"] = groups.update.origin;
  projection["update.update_source"] = groups.update.updateSource;
  projection["update.update_source_origin"] = groups.update.updateSourceOrigin;
  projection["scan.fcx_mode"] = groups.scan.fcxMode;
  projection["scan.fcx_mode_origin"] = groups.scan.fcxModeOrigin;
  projection["scan.simplify_logs"] = groups.scan.simplifyLogs;
  projection["scan.simplify_logs_origin"] = groups.scan.simplifyLogsOrigin;
  projection["scan.show_statistics"] = groups.scan.showStatistics;
  projection["scan.show_statistics_origin"] = groups.scan.showStatisticsOrigin;
  projection["scan.formid_value_lookup"] = groups.scan.formidValueLookup;
  projection["scan.formid_value_lookup_origin"] = groups.scan.formidValueLookupOrigin;
  projection["scan.formid_databases"] = groups.scan.formidDatabases;
  projection["scan.formid_databases_origin"] = groups.scan.formidDatabasesOrigin;
  projection["scan.move_unsolved_logs"] = groups.scan.moveUnsolvedLogs;
  projection["scan.move_unsolved_logs_origin"] = groups.scan.moveUnsolvedLogsOrigin;
  projection["scan.unsolved_logs_destination"] = groups.scan.unsolvedLogsDestination ?? null;
  projection["scan.unsolved_logs_destination_origin"] = groups.scan.unsolvedLogsDestinationOrigin;
  projection["scan.custom_scan_input"] = groups.scan.customScanInput ?? null;
  projection["scan.custom_scan_input_origin"] = groups.scan.customScanInputOrigin;
  projection["scan.game_version_selection"] = groups.scan.gameVersionSelection;
  projection["scan.game_version_selection_origin"] = groups.scan.gameVersionSelectionOrigin;
  projection["scan.max_concurrent_scans"] = groups.scan.maxConcurrentScans;
  projection["scan.max_concurrent_scans_origin"] = groups.scan.maxConcurrentScansOrigin;
  projection["setup.managed_game"] = (groups.setup.managedGame === classic.JsGameId.Fallout4 ? "Fallout4" : "unexpected-game");
  projection["setup.managed_game_origin"] = groups.setup.managedGameOrigin;
  projection["setup.game_version_selection"] = groups.setup.gameVersionSelection;
  projection["setup.game_version_selection_origin"] = groups.setup.gameVersionSelectionOrigin;
  projection["setup.game_root"] = groups.setup.gameRoot ?? null;
  projection["setup.game_root_origin"] = groups.setup.gameRootOrigin;
  projection["setup.game_executable"] = groups.setup.gameExecutable ?? null;
  projection["setup.game_executable_origin"] = groups.setup.gameExecutableOrigin;
  projection["setup.documents_root"] = groups.setup.documentsRoot ?? null;
  projection["setup.documents_root_origin"] = groups.setup.documentsRootOrigin;
  projection["setup.ini_folder"] = groups.setup.iniFolder ?? null;
  projection["setup.ini_folder_origin"] = groups.setup.iniFolderOrigin;
  projection["setup.mods_root"] = groups.setup.modsRoot ?? null;
  projection["setup.mods_root_origin"] = groups.setup.modsRootOrigin;
  projection["setup.custom_scan_input"] = groups.setup.customScanInput ?? null;
  projection["setup.custom_scan_input_origin"] = groups.setup.customScanInputOrigin;
  projection["setup.papyrus_log"] = groups.setup.papyrusLog ?? null;
  projection["setup.papyrus_log_origin"] = groups.setup.papyrusLogOrigin;
  projection["preferences.auto_switch_after_scan"] = groups.preferences.autoSwitchAfterScan;
  projection["preferences.auto_switch_after_scan_origin"] = groups.preferences.autoSwitchAfterScanOrigin;
  projection["preferences.auto_refresh_interval_ms"] = groups.preferences.autoRefreshIntervalMs;
  projection["preferences.auto_refresh_interval_ms_origin"] = groups.preferences.autoRefreshIntervalMsOrigin;
  projection["tui.active_tab"] = groups.tui.activeTab;
  projection["tui.active_tab_origin"] = groups.tui.activeTabOrigin;
  projection["tui.results_panel_width"] = groups.tui.resultsPanelWidth;
  projection["tui.results_panel_width_origin"] = groups.tui.resultsPanelWidthOrigin;
  projection["tui.sort_ascending"] = groups.tui.sortAscending;
  projection["tui.sort_ascending_origin"] = groups.tui.sortAscendingOrigin;
  projection["main_tab.maximized"] = groups.mainTab.maximized;
  projection["main_tab.maximized_origin"] = groups.mainTab.maximizedOrigin;
  projection["main_tab.width"] = groups.mainTab.width;
  projection["main_tab.width_origin"] = groups.mainTab.widthOrigin;
  projection["main_tab.height"] = groups.mainTab.height;
  projection["main_tab.height_origin"] = groups.mainTab.heightOrigin;
  projection["backups_tab.maximized"] = groups.backupsTab.maximized;
  projection["backups_tab.maximized_origin"] = groups.backupsTab.maximizedOrigin;
  projection["backups_tab.width"] = groups.backupsTab.width;
  projection["backups_tab.width_origin"] = groups.backupsTab.widthOrigin;
  projection["backups_tab.height"] = groups.backupsTab.height;
  projection["backups_tab.height_origin"] = groups.backupsTab.heightOrigin;
  projection["articles_tab.maximized"] = groups.articlesTab.maximized;
  projection["articles_tab.maximized_origin"] = groups.articlesTab.maximizedOrigin;
  projection["articles_tab.width"] = groups.articlesTab.width;
  projection["articles_tab.width_origin"] = groups.articlesTab.widthOrigin;
  projection["articles_tab.height"] = groups.articlesTab.height;
  projection["articles_tab.height_origin"] = groups.articlesTab.heightOrigin;
  projection["results_tab.maximized"] = groups.resultsTab.maximized;
  projection["results_tab.maximized_origin"] = groups.resultsTab.maximizedOrigin;
  projection["results_tab.width"] = groups.resultsTab.width;
  projection["results_tab.width_origin"] = groups.resultsTab.widthOrigin;
  projection["results_tab.height"] = groups.resultsTab.height;
  projection["results_tab.height_origin"] = groups.resultsTab.heightOrigin;
  return {projection};
}
